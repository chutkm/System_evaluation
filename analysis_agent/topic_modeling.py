def normalize_text(text: str) -> List[str]:
    """
    Приводит текст к нижнему регистру, удаляет знаки препинания
    и разбивает на слова (токены), убирая стоп-слова.
    """
    text = text.lower()
    # Оставляем только буквы, цифры и пробелы
    text = re.sub(r"[^\w\s]", " ", text)
    words = text.split()
    # Фильтруем стоп-слова и короткие слова (< 3 букв)
    return [w for w in words if w not in STOP_WORDS and len(w) > 2]

def extract_topics(text: str, top_n: int = 3) -> List[str]:
    tokens = normalize_text(text)
    
    if not tokens:
        return []

    topic_scores: Dict[str, int] = {}

    # 1️⃣ Подсчет совпадений по словарю
    for topic, keywords in TOPIC_DICTIONARY.items():
        score = 0
        # Нормализуем ключевые слова тоже (просто нижний регистр и сплит, если там фразы)
        # В данном словаре у нас в основном отдельные слова или простые фразы.
        # Для простоты проверяем вхождение каждого токена текста в список ключевых слов
        
        # Превращаем ключевые слова в плоский список токенов для сравнения
        # (если в словаре есть фразы "слишком быстро", разбиваем их)
        normalized_keywords = set()
        for kw in keywords:
            normalized_keywords.update(normalize_text(kw))
            
        for token in tokens:
            if token in normalized_keywords:
                score += 1
        
        if score > 0:
            topic_scores[topic] = score

    # Если нашли темы по ключевым словам
    if topic_scores:
        # Сортируем темы по количеству совпадений (от большего к меньшему)
        sorted_topics = sorted(topic_scores.items(), key=lambda x: x[1], reverse=True)
        return [topic for topic, score in sorted_topics[:top_n]]

    # 2️⃣ Fallback (если прямых совпадений нет)
    # Вместо возврата случайных слов ("большое", "за"), пытаемся найти тему,
    # которая имеет хоть какое-то пересечение, или возвращаем пустой список / общую тему.
    # Здесь можно подключить семантический поиск (cosine similarity), если нужно сложнее.
    # Для текущего уровня вернем список наиболее вероятных тем на основе длины ключевых слов
    # или просто вернем пустой список, чтобы не вводить в заблуждение.
    
    # Вариант: Вернуть топ-3 самых частых темы из всего словаря (как заглушку)
    # Но лучше вернуть сообщение, что тема не определена точно.
    return ["тема не определена точно"] 

